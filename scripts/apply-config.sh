#!/usr/bin/env bash
# Render /opt/athan/web/config.js from /etc/default/athan so the web page and the
# adhan scheduler always use the same location and calculation settings.
set -euo pipefail
CONF=/etc/default/athan
WEB=/opt/athan/web
[ -f "$CONF" ] || { echo "Missing $CONF (copy athan.conf.example there first)"; exit 1; }
# shellcheck source=/dev/null
. "$CONF"

LANGS_JSON=""
for l in ${TRANSLATION_LANGS:-en}; do LANGS_JSON="${LANGS_JSON}\"${l}\","; done
LANGS_JSON="[${LANGS_JSON%,}]"

# NEWS_VIDEO_CHANNELS="Name|UCxxxx;Name|UCyyyy" -> [{"name":"Name","id":"UCxxxx"},...]
# Left empty, the key is omitted entirely so the channel list baked into index.html is used.
CHANS_LINE=""
if [ -n "${NEWS_VIDEO_CHANNELS:-}" ]; then
  CHANS_JSON=""
  old_ifs=$IFS; IFS=';'
  for part in $NEWS_VIDEO_CHANNELS; do
    IFS=$old_ifs
    case "$part" in *"|"*) ;; *) continue ;; esac
    nm=${part%%|*}; id=${part#*|}
    nm=$(printf '%s' "$nm" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//; s/["\\]//g')
    id=$(printf '%s' "$id" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//; s/["\\]//g')
    [ -n "$nm" ] && [ -n "$id" ] && CHANS_JSON="${CHANS_JSON}{\"name\":\"${nm}\",\"id\":\"${id}\"},"
    IFS=';'
  done
  IFS=$old_ifs
  [ -n "$CHANS_JSON" ] && CHANS_LINE="  newsChannels: [${CHANS_JSON%,}],"
fi

# MARKETS_FEATURED="CL=F;BZ=F" -> ["CL=F","BZ=F"]: symbols shown large in their own top row.
FEAT_JSON=""
old_ifs=$IFS; IFS=';'
for s in ${MARKETS_FEATURED-CL=F;BZ=F}; do
  s=$(printf '%s' "$s" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//; s/["\\]//g')
  [ -n "$s" ] && FEAT_JSON="${FEAT_JSON}\"${s}\","
done
IFS=$old_ifs
FEAT_JSON="[${FEAT_JSON%,}]"

cat > "$WEB/config.js" <<JS
// Generated by apply-config.sh from $CONF on $(date '+%F %T') -- edit $CONF, not this file.
window.ATHAN_CONFIG = {
  latitude: ${LATITUDE},
  longitude: ${LONGITUDE},
  method: ${METHOD:-2},
  school: ${SCHOOL:-0},
  tune: "${TUNE:-}",
  langs: ${LANGS_JSON},
  textScaleMax: ${TEXT_SCALE_MAX:-1.6},
  translationSeconds: ${TRANSLATION_SECONDS:-12},
  slideSeconds: {
    ayah: ${AYAH_SECONDS:-24}, hadith: ${AYAH_SECONDS:-24},
    forecast: ${FORECAST_SECONDS:-20}, breaking: ${BREAKING_SECONDS:-30}, newsvideo: ${NEWS_VIDEO_SECONDS:-120},
    markets: ${MARKETS_SECONDS:-70}, week: ${WEEK_SECONDS:-20}, lists: ${LISTS_SECONDS:-20}
  },
  news: ${NEWS_TICKER:-true},
  usNews: ${US_NEWS_TICKER:-true},
  usNewsLabel: "${US_NEWS_LABEL:-US MARKETS}",
  weather: ${WEATHER:-true},
  forecast: ${FORECAST:-true},
  markets: ${MARKETS_SLIDE:-true},
  marketsFeatured: ${FEAT_JSON},
  breaking: ${BREAKING_NEWS:-true},
  breakingCount: ${BREAKING_COUNT:-5},
  newsVideo: ${NEWS_VIDEO:-false},
  newsVideoTitle: "${NEWS_VIDEO_TITLE:-US News Live}",
  newsMuted: ${NEWS_VIDEO_MUTED:-true},
  newsVolume: ${NEWS_VIDEO_VOLUME:-60},
${CHANS_LINE}
  newsSpeed: ${NEWS_SPEED:-0.055},
  newsLoopSeconds: ${NEWS_LOOP_SECONDS:-null},
  family: ${FAMILY:-true}
};
JS
chmod 644 "$WEB/config.js"
echo "Wrote $WEB/config.js. The TV picks it up within 3 minutes (or: systemctl restart lightdm)."
